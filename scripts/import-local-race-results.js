#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const mysql = require('mysql2/promise');

const repoRoot = path.resolve(__dirname, '..');

function usage() {
  console.log(`Usage:
  node scripts/import-local-race-results.js --input /path/results.json[|jsonl] [--dry-run] [--source-batch-size 10]

Environment is loaded from .env.local. This imports local result-book payloads
generated by scripts/parse-race-results.py and is idempotent by source + result key.`);
}

function parseArgs(argv) {
  const args = { input: '', dryRun: false, sourceBatchSize: 10, resultBatchSize: 200 };
  for (let i = 2; i < argv.length; i += 1) {
    const item = argv[i];
    if (item === '--dry-run') args.dryRun = true;
    else if (item === '--input') args.input = argv[++i] || '';
    else if (item === '--source-batch-size') args.sourceBatchSize = Math.max(1, Number(argv[++i] || 10));
    else if (item === '--result-batch-size') args.resultBatchSize = Math.max(20, Number(argv[++i] || 200));
    else if (item === '--help' || item === '-h') args.help = true;
  }
  return args;
}

function loadEnv() {
  const envPath = path.join(repoRoot, '.env.local');
  const env = { ...process.env };
  if (!fs.existsSync(envPath)) return env;
  for (const line of fs.readFileSync(envPath, 'utf8').split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const index = trimmed.indexOf('=');
    if (index < 0) continue;
    const key = trimmed.slice(0, index).trim();
    let value = trimmed.slice(index + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    env[key] = value;
  }
  return env;
}

function readPayloads(filePath) {
  const text = fs.readFileSync(filePath, 'utf8').trim();
  if (!text) return [];
  if (filePath.endsWith('.jsonl')) {
    return text.split(/\r?\n/).filter(Boolean).map((line) => JSON.parse(line));
  }
  const parsed = JSON.parse(text);
  return Array.isArray(parsed) ? parsed : [parsed];
}

function sourcePriority(payload) {
  const sourceName = `${payload.source?.file_name || ''} ${payload.source?.original_path || ''}`;
  let score = 0;
  if (/成绩册|总结册|汇总|总成绩|全册|总排名|大排名/.test(sourceName)) score += 50;
  if (/成绩公告|成绩单|预赛|决赛|大师组|公开组|男子|女子|单项|分组/.test(sourceName)) score += 10;
  if (/jpg|jpeg|png|图片/i.test(sourceName)) score -= 20;
  score += Array.isArray(payload.results) ? Math.min(payload.results.length, 200) / 10 : 0;
  return score;
}

function eventKey(payload) {
  const event = payload.event || {};
  return `${event.start_date || ''}|${String(event.name || '').trim()}`;
}

function strictResultKey(result) {
  return [
    result.gender_group || '公开组',
    result.discipline || '',
    result.board_class || '',
    result.round_label || '',
    result.rank_position || '',
    normalizedName(result.athlete_name_snapshot || result.athlete_name || ''),
    String(result.finish_time || '').trim(),
  ].join('|');
}

function relaxedResultKey(result) {
  return [
    result.discipline || '',
    normalizedName(result.athlete_name_snapshot || result.athlete_name || ''),
    String(result.finish_time || '').trim(),
  ].join('|');
}

function dedupePayloads(payloads) {
  const sorted = payloads
    .map((payload, originalIndex) => ({ payload, originalIndex, priority: sourcePriority(payload) }))
    .sort((a, b) => {
      if (eventKey(a.payload) !== eventKey(b.payload)) return eventKey(a.payload).localeCompare(eventKey(b.payload));
      if (b.priority !== a.priority) return b.priority - a.priority;
      return a.originalIndex - b.originalIndex;
    });

  const seenStrict = new Set();
  const seenRelaxed = new Map();
  let skipped = 0;
  const output = [];

  for (const entry of sorted) {
    const payload = entry.payload;
    const evKey = eventKey(payload);
    const nextResults = [];
    const results = Array.isArray(payload.results) ? payload.results : [];

    for (const result of results) {
      if (!result.athlete_name_snapshot || !result.discipline || !result.finish_time) {
        skipped += 1;
        continue;
      }

      const strictKey = `${evKey}|${strictResultKey(result)}`;
      const relaxedKey = `${evKey}|${relaxedResultKey(result)}`;
      if (seenStrict.has(strictKey)) {
        skipped += 1;
        continue;
      }

      const relaxedOwner = seenRelaxed.get(relaxedKey);
      if (relaxedOwner && relaxedOwner.priority >= entry.priority) {
        skipped += 1;
        continue;
      }

      seenStrict.add(strictKey);
      seenRelaxed.set(relaxedKey, { priority: entry.priority });
      nextResults.push(result);
    }

    output.push({
      ...payload,
      results: nextResults,
      source: {
        ...(payload.source || {}),
        metadata: {
          ...(payload.source?.metadata || {}),
          import_priority: entry.priority,
          dedupe_applied: true,
        },
      },
    });
  }

  return { payloads: output, skipped };
}

function slugify(name, startDate) {
  const ascii = name
    .normalize('NFKD')
    .replace(/[^\w\s-]/g, '')
    .trim()
    .replace(/\s+/g, '-')
    .toLowerCase();
  if (ascii) return ascii.slice(0, 120);
  const hash = crypto.createHash('sha1').update(`${startDate || ''}:${name}`).digest('hex').slice(0, 10);
  return `local-race-${(startDate || 'unknown').replaceAll('-', '')}-${hash}`;
}

function parseTimeToSeconds(input) {
  const raw = String(input || '').trim();
  if (!raw) return null;
  if (/^\d+(\.\d+)?$/.test(raw)) return Number(raw);
  const quoteMatch = raw.match(/^(\d+)'(\d+(?:\.\d+)?)"?$/);
  if (quoteMatch) return Number(quoteMatch[1]) * 60 + Number(quoteMatch[2]);
  const dottedTime = raw.match(/^(\d+):(\d{2})\.(\d{2})\.(\d{1,3})$/);
  if (dottedTime) return Number(dottedTime[1]) * 3600 + Number(dottedTime[2]) * 60 + Number(`${dottedTime[3]}.${dottedTime[4]}`);
  const parts = raw.split(':').map((part) => part.trim());
  if (parts.some((part) => !/^\d+(\.\d+)?$/.test(part))) return null;
  if (parts.length === 2) return Number(parts[0]) * 60 + Number(parts[1]);
  if (parts.length === 3) return Number(parts[0]) * 3600 + Number(parts[1]) * 60 + Number(parts[2]);
  return null;
}

function normalizedName(name) {
  return String(name || '').replace(/\s+/g, '').toLowerCase();
}

async function resolveAthleteId(connection, result, athleteCache) {
  if (result.athlete_id) return Number(result.athlete_id);
  const name = String(result.athlete_name_snapshot || result.athlete_name || '').trim();
  if (!name) return null;
  const cacheKey = normalizedName(name);
  if (athleteCache.has(cacheKey)) return athleteCache.get(cacheKey);

  const [identityRows] = await connection.execute(
    `SELECT athlete_id FROM sup_athlete_identity_links
     WHERE normalized_name = ? AND status = 'confirmed' AND athlete_id IS NOT NULL
     ORDER BY confidence DESC, link_id ASC LIMIT 1`,
    [normalizedName(name)]
  );
  if (identityRows.length) {
    const athleteId = Number(identityRows[0].athlete_id);
    athleteCache.set(cacheKey, athleteId);
    return athleteId;
  }

  const [existingRows] = await connection.execute(
    `SELECT athlete_id FROM sup_athletes
     WHERE name = ?
     ORDER BY CASE status WHEN 'published' THEN 0 ELSE 1 END, athlete_id ASC
     LIMIT 5`,
    [name]
  );
  if (existingRows.length) {
    const athleteId = Number(existingRows[0].athlete_id);
    await connection.execute(
      `INSERT IGNORE INTO sup_athlete_identity_links
        (athlete_id, normalized_name, display_name, gender_hint, team_hint, nationality_hint, confidence, status, note)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)`,
      [
        athleteId,
        normalizedName(name),
        name,
        result.gender_group || null,
        result.team_name || null,
        result.nationality_snapshot || null,
        existingRows.length > 1 ? 0.5 : 0.9,
        existingRows.length > 1 ? 'pending' : 'confirmed',
        existingRows.length > 1 ? '本地成绩册导入时发现同名候选，需后台确认' : '本地成绩册导入自动确认同名运动员',
      ]
    );
    athleteCache.set(cacheKey, athleteId);
    return athleteId;
  }

  const [insertResult] = await connection.execute(
    `INSERT INTO sup_athletes (name, nationality, discipline, bio, status)
     VALUES (?, ?, 'race', ?, 'draft')`,
    [
      name,
      result.nationality_snapshot || '中国',
      '由本地成绩册导入自动生成的运动员草稿档案，待补充完整人物资料。',
    ]
  );
  const athleteId = Number(insertResult.insertId);
  await connection.execute(
    `INSERT IGNORE INTO sup_athlete_identity_links
      (athlete_id, normalized_name, display_name, gender_hint, team_hint, nationality_hint, confidence, status, note)
     VALUES (?, ?, ?, ?, ?, ?, 0.85, 'confirmed', '本地成绩册导入自动创建草稿运动员')`,
    [athleteId, normalizedName(name), name, result.gender_group || null, result.team_name || null, result.nationality_snapshot || null]
  );
  athleteCache.set(cacheKey, athleteId);
  return athleteId;
}

async function syncAthleteRaceTimesBatch(connection, athleteIds) {
  const ids = [...new Set(athleteIds.map(Number).filter(Number.isFinite))];
  if (!ids.length) return 0;
  const placeholders = ids.map(() => '?').join(',');
  const [rows] = await connection.execute(
    `SELECT er.athlete_id, er.discipline, er.round_label, er.result_label, er.finish_time, e.start_date, e.event_id, e.name AS event_name
     FROM sup_event_results er
     INNER JOIN sup_events e ON e.event_id = er.event_id
     INNER JOIN sup_event_result_sources src ON src.source_id = er.source_id
     WHERE er.athlete_id IN (${placeholders})
       AND (src.parser_name IN ('parse-race-results.py', 'local-race-results-import') OR src.original_path LIKE '%/桨板赛事/%')
     ORDER BY er.athlete_id ASC, e.start_date DESC, er.rank_position ASC`,
    ids
  );
  const grouped = new Map(ids.map((id) => [id, []]));
  for (const row of rows) {
    const athleteId = Number(row.athlete_id);
    if (!grouped.has(athleteId)) grouped.set(athleteId, []);
    grouped.get(athleteId).push({
      distance: row.discipline,
      year: row.start_date ? new Date(row.start_date).getFullYear() : undefined,
      event: row.event_name,
      event_id: row.event_id,
      round: row.round_label || undefined,
      result: row.result_label || undefined,
      time: row.finish_time,
    });
  }
  for (const [athleteId, raceTimes] of grouped.entries()) {
    await connection.execute('UPDATE sup_athletes SET race_times = ? WHERE athlete_id = ?', [JSON.stringify(raceTimes), athleteId]);
  }
  return grouped.size;
}

async function upsertEvent(connection, event) {
  const name = String(event.name || '').trim();
  if (!name) throw new Error('event.name is required');
  const startDate = event.start_date || null;
  const [existing] = await connection.execute(
    `SELECT event_id FROM sup_events WHERE name = ? AND (start_date <=> ?) ORDER BY event_id ASC LIMIT 1`,
    [name, startDate]
  );
  if (existing.length) return Number(existing[0].event_id);

  const slug = slugify(name, startDate);
  const [insertResult] = await connection.execute(
    `INSERT INTO sup_events
      (name, slug, event_type, province, city, venue, start_date, end_date, description,
       star_level, score_coefficient, source_scope, result_status, result_source_note,
       result_last_verified_at, status, event_status)
     VALUES (?, ?, 'race', ?, ?, ?, ?, ?, ?, ?, ?, ?, 'partial', ?, NOW(), 'published', 'completed')
     ON DUPLICATE KEY UPDATE event_id = LAST_INSERT_ID(event_id)`,
    [
      name,
      slug,
      event.province || null,
      event.city || null,
      event.venue || null,
      startDate,
      event.end_date || startDate,
      event.description || null,
      event.star_level || null,
      event.score_coefficient || null,
      event.source_scope || '本地成绩册导入',
      event.result_source_note || '本地成绩册导入',
    ]
  );
  return Number(insertResult.insertId);
}

async function upsertSource(connection, eventId, source, resultsLength) {
  const metadata = {
    ...(source.metadata || {}),
    source_kind: source.source_kind || source.metadata?.source_kind || 'local_result_book',
  };
  const [existing] = await connection.execute(
    `SELECT source_id FROM sup_event_result_sources
     WHERE event_id = ? AND ((original_path IS NOT NULL AND original_path = ?) OR (file_name = ? AND COALESCE(source_url, '') = COALESCE(?, '')))
     ORDER BY source_id ASC LIMIT 1`,
    [eventId, source.original_path || null, source.file_name || '', source.source_url || null]
  );
  const status = resultsLength ? 'imported' : (source.parser_status || 'pending_review');
  if (existing.length) {
    const sourceId = Number(existing[0].source_id);
    await connection.execute(
      `UPDATE sup_event_result_sources
       SET source_url = ?, parser_name = ?, parser_status = ?, parser_note = ?, extracted_rows = ?, imported_rows = ?, metadata = ?
       WHERE source_id = ?`,
      [
        source.source_url || null,
        source.parser_name || 'local-race-results-import',
        status,
        source.parser_note || null,
        Number(source.extracted_rows || resultsLength || 0),
        resultsLength,
        JSON.stringify(metadata),
        sourceId,
      ]
    );
    return sourceId;
  }

  const [insertResult] = await connection.execute(
    `INSERT INTO sup_event_result_sources
      (event_id, original_path, file_name, file_type, source_url, parser_name, parser_status, parser_note, extracted_rows, imported_rows, metadata)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
    [
      eventId,
      source.original_path || null,
      source.file_name,
      source.file_type || 'unknown',
      source.source_url || null,
      source.parser_name || 'local-race-results-import',
      status,
      source.parser_note || null,
      Number(source.extracted_rows || resultsLength || 0),
      resultsLength,
      JSON.stringify(metadata),
    ]
  );
  return Number(insertResult.insertId);
}

async function insertResultRow(connection, eventId, sourceId, source, result, athleteCache) {
  const athleteId = await resolveAthleteId(connection, result, athleteCache);
  const athleteName = String(result.athlete_name_snapshot || result.athlete_name || '').trim();
  await connection.execute(
    `INSERT INTO sup_event_results (
      event_id, athlete_id, athlete_name_snapshot, bib_number, gender_group, discipline, board_class, round_label,
      rank_position, result_label, finish_time, time_seconds, points, team_name, nationality_snapshot,
      source_type, source_id, source_title, source_locator, source_url, source_note, parse_confidence, review_status, is_verified
    ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'official', ?, ?, ?, ?, ?, ?, ?, ?)
    ON DUPLICATE KEY UPDATE
      athlete_id = VALUES(athlete_id),
      bib_number = VALUES(bib_number),
      board_class = VALUES(board_class),
      result_label = VALUES(result_label),
      finish_time = VALUES(finish_time),
      time_seconds = VALUES(time_seconds),
      points = VALUES(points),
      team_name = VALUES(team_name),
      source_id = VALUES(source_id),
      source_title = VALUES(source_title),
      source_locator = VALUES(source_locator),
      source_url = VALUES(source_url),
      source_note = VALUES(source_note),
      parse_confidence = VALUES(parse_confidence),
      review_status = VALUES(review_status),
      is_verified = VALUES(is_verified)`,
    [
      eventId,
      athleteId,
      athleteName,
      result.bib_number || null,
      result.gender_group || '公开组',
      result.discipline,
      result.board_class || null,
      result.round_label || null,
      Number(result.rank_position),
      result.result_label || null,
      String(result.finish_time || ''),
      parseTimeToSeconds(result.finish_time),
      typeof result.points === 'number' && Number.isFinite(result.points) ? result.points : null,
      result.team_name || null,
      result.nationality_snapshot || null,
      sourceId,
      result.source_title || source.file_name || null,
      result.source_locator || null,
      result.source_url || source.source_url || null,
      result.source_note || null,
      typeof result.parse_confidence === 'number' ? result.parse_confidence : 1,
      result.review_status || 'confirmed',
      result.is_verified === false ? 0 : 1,
    ]
  );
  return athleteId;
}

async function importPayload(connection, payload, dryRun, athleteCache) {
  const results = Array.isArray(payload.results) ? payload.results.filter((row) => row.athlete_name_snapshot && row.discipline && row.finish_time) : [];
  if (dryRun) {
    return { eventId: null, sourceId: null, results: results.length, athletes: 0 };
  }
  await connection.beginTransaction();
  try {
    const eventId = await upsertEvent(connection, payload.event || {});
    const sourceId = await upsertSource(connection, eventId, payload.source || {}, results.length);
    const touchedAthletes = new Set();
    for (const result of results) {
      const athleteId = await insertResultRow(connection, eventId, sourceId, payload.source || {}, result, athleteCache);
      if (athleteId) touchedAthletes.add(athleteId);
    }
    await connection.execute(
      `UPDATE sup_events
       SET result_status = CASE WHEN ? > 0 THEN 'extended_complete' ELSE result_status END,
           result_source_note = COALESCE(result_source_note, ?),
           result_last_verified_at = CASE WHEN ? > 0 THEN NOW() ELSE result_last_verified_at END
       WHERE event_id = ?`,
      [results.length, payload.source?.file_name || '本地成绩册导入', results.length, eventId]
    );
    await connection.commit();
    return { eventId, sourceId, results: results.length, athletes: touchedAthletes.size, athleteIds: [...touchedAthletes] };
  } catch (error) {
    await connection.rollback();
    throw error;
  }
}

function chunk(array, size) {
  const chunks = [];
  for (let i = 0; i < array.length; i += size) chunks.push(array.slice(i, i + size));
  return chunks;
}

async function importPayloadBatch(connection, payloads, args, summary, athleteCache, batchIndex, totalBatches) {
  const touchedAthletes = new Set();
  console.log(`batch ${batchIndex}/${totalBatches} sources=${payloads.length} start`);
  for (const payload of payloads) {
    const result = await importPayload(connection, payload, args.dryRun, athleteCache);
    summary.sources += 1;
    summary.results += result.results;
    summary.athletes += result.athletes;
    if (result.athleteIds) result.athleteIds.forEach((id) => touchedAthletes.add(id));
    console.log(`${args.dryRun ? 'checked' : 'imported'} source=${payload.source?.file_name || '-'} results=${result.results}`);
  }
  if (!args.dryRun) {
    const ids = [...touchedAthletes];
    for (const group of chunk(ids, args.resultBatchSize)) {
      await syncAthleteRaceTimesBatch(connection, group);
    }
    console.log(`batch ${batchIndex}/${totalBatches} syncedAthletes=${ids.length}`);
  }
}

async function main() {
  const args = parseArgs(process.argv);
  if (args.help || !args.input) {
    usage();
    process.exit(args.help ? 0 : 1);
  }
  const rawPayloads = readPayloads(args.input);
  const { payloads, skipped } = dedupePayloads(rawPayloads);
  if (args.dryRun) {
    const summary = payloads.reduce((acc, payload) => {
      acc.sources += 1;
      acc.results += Array.isArray(payload.results) ? payload.results.length : 0;
      return acc;
    }, { sources: 0, results: 0 });
    for (const payload of payloads) {
      console.log(`checked source=${payload.source?.file_name || '-'} results=${Array.isArray(payload.results) ? payload.results.length : 0}`);
    }
    console.log(`dry-run sources=${summary.sources} results=${summary.results} skippedDuplicates=${skipped}`);
    return;
  }
  const env = loadEnv();
  const connection = await mysql.createConnection({
    host: env.MYSQL_HOST || 'localhost',
    port: Number(env.MYSQL_PORT || 3306),
    user: env.MYSQL_USER || 'root',
    password: env.MYSQL_PASSWORD || '',
    database: env.MYSQL_DATABASE || 'sport_hacker',
  });
  const summary = { sources: 0, results: 0, athletes: 0 };
  const athleteCache = new Map();
  try {
    const batches = chunk(payloads, args.sourceBatchSize);
    for (let index = 0; index < batches.length; index += 1) {
      await importPayloadBatch(connection, batches[index], args, summary, athleteCache, index + 1, batches.length);
    }
  } finally {
    await connection.end();
  }
  console.log(`${args.dryRun ? 'dry-run' : 'done'} sources=${summary.sources} results=${summary.results} touchedAthletes=${summary.athletes} skippedDuplicates=${skipped}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
